"""
math_utils.py
A simple Python module containing reusable mathematical utility functions.
"""

def add(a, b):
    """Return the sum of two numbers."""
    return a + b

def subtract(a, b):
    """Return the difference between two numbers."""
    return a - b

def is_even(number):
    """Return True if the number is even, False otherwise."""
    return number % 2 == 0